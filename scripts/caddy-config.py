r"""Write the Caddyfile for the phones (stage 6). Routes come from the backend, never typed by hand:
MOBILE + every route of the pairing router + GET /health. Everything else is 404 at Caddy.

Usage (project root, venv):
    .venv\Scripts\python scripts\caddy-config.py --output C:\ITGlasses-Caddy\Caddyfile --bind 192.168.1.50

--bind is the PC's LAN address; without it, the host of ITGLASSES_PAIRING_ORIGIN is used.

No secrets: the certificate and key are referenced by path, never read. The backend is imported only
inside phone_routes(), so loading this file (as the tests do) imports nothing and writes nothing.
"""
import argparse
import os
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
# Run as a program (python scripts\caddy-config.py) the project root is not on sys.path: add it before any
# backend import, or "import backend" fails. Adding a path imports nothing.
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

# 150 s: above the backend's own LLM timeout (settings.timeout_seconds, 120 s on CPU) so its error reaches
# the phone, and above OkHttp's readTimeout (120 s) and below its callTimeout (180 s) in the APK, so Caddy
# never cuts a request the phone is still waiting for.
RESPONSE_HEADER_TIMEOUT = "150s"
DIAL_TIMEOUT = "5s"
MAX_BODY = "2MB"  # The backend enforces the exact audio limit (MAX_AUDIO, about 0.96 MB).

TEMPLATE = """# Generated by scripts/caddy-config.py from the backend routes. Do not edit by hand.
{{
\tadmin off
\tauto_https disable_redirects
\tservers {{
\t\tprotocols h1 h2
\t\ttimeouts {{
\t\t\tread_header 10s
\t\t\tidle 2m
\t\t}}
\t}}
}}

:{port} {{
\tbind {bind}
\ttls {cert} {key}
\trequest_body {{
\t\tmax_size {max_body}
\t}}
{handlers}
\thandle {{
\t\trespond 404
\t}}
}}
"""

HANDLER = """\t@{name} {{
\t\tmethod {method}
\t\tpath {paths}
\t}}
\thandle @{name} {{
\t\treverse_proxy 127.0.0.1:{upstream} {{
\t\t\ttransport http {{
\t\t\t\tdial_timeout {dial}
\t\t\t\tresponse_header_timeout {header}
\t\t\t}}
\t\t}}
\t}}"""


def validate(routes):
    """Publish only exact, prefixed phone paths: never the admin panel, wildcards or path parameters."""
    for method, path in routes:
        if not (path == "/health" or path.startswith("/api/v1/")):
            raise SystemExit(f"Refusing to publish {method} {path}: not under /api/v1")
        if path.startswith("/api/v1/admin") or "*" in path or "{" in path or " " in path:
            raise SystemExit(f"Refusing to publish {method} {path}")
    return routes


def phone_routes():
    from backend.app.pairing.routes import MOBILE, router
    routes = set(MOBILE) | {(m, r.path) for r in router.routes for m in r.methods} | {("GET", "/health")}
    return validate(routes)


def caddyfile(bind, port, cert, key, routes=None, upstream=None):
    if upstream is None:
        from backend.app.core.config import settings
        upstream = settings.port
    routes = validate(routes if routes is not None else phone_routes())
    handlers = []
    for method in sorted({m for m, _ in routes}):
        paths = " ".join(sorted(p for m, p in routes if m == method))
        handlers.append(HANDLER.format(name="phone_" + method.lower(), method=method, paths=paths,
                                       upstream=upstream, dial=DIAL_TIMEOUT, header=RESPONSE_HEADER_TIMEOUT))
    return TEMPLATE.format(port=port, bind=bind, cert=cert, key=key, max_body=MAX_BODY,
                           handlers="\n".join(handlers))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", required=True, type=Path)
    origin_host = urlsplit(os.environ.get("ITGLASSES_PAIRING_ORIGIN", "").strip()).hostname
    parser.add_argument("--bind", default=origin_host, required=origin_host is None,
                        help="LAN address of this PC, e.g. 192.168.1.50 (default: the host of ITGLASSES_PAIRING_ORIGIN)")
    parser.add_argument("--port", type=int, default=8443)
    parser.add_argument("--cert", default="C:/ITGlasses-Caddy/certs/server.crt")
    parser.add_argument("--key", default="C:/ITGlasses-Caddy/certs/server.key")
    args = parser.parse_args(argv)
    text = caddyfile(args.bind, args.port, args.cert, args.key)
    # UTF-8 without BOM and LF: a PowerShell ">" redirect would write UTF-16, which Caddy cannot read.
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"Caddyfile written to {args.output}")


if __name__ == "__main__":
    sys.dont_write_bytecode = True  # No __pycache__ from a one-off run.
    main()
